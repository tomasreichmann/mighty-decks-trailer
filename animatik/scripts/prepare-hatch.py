def extract(image, outline, filename):
    pixels = np.array(image)
    shape = np.zeros(pixels.shape[:2], dtype=np.uint8)
    cv2.fillPoly(shape, [np.asarray(outline, np.int32)], 255)
    nearby = cv2.dilate(shape, np.ones((9, 9), np.uint8)) > 0
    core = cv2.erode(shape, np.ones((11, 11), np.uint8)) > 0
    mask = np.full(shape.shape, cv2.GC_BGD, dtype=np.uint8)
    mask[nearby] = cv2.GC_PR_BGD
    mask[shape > 0] = cv2.GC_PR_FGD
    mask[core] = cv2.GC_FGD
    mask[pixels[:, :, 3] < 4] = cv2.GC_BGD
    cv2.setNumThreads(1)
    cv2.setRNGSeed(17)
    cv2.grabCut(cv2.cvtColor(pixels, cv2.COLOR_RGBA2BGR), mask, None,
                np.zeros((1, 65)), np.zeros((1, 65)), 4, cv2.GC_INIT_WITH_MASK)
    alpha = ((mask % 2) * 255).astype(np.uint8)
    pixels[:, :, 3] = np.minimum(pixels[:, :, 3], cv2.GaussianBlur(alpha, (3, 3), .5))
    pixels[pixels[:, :, 3] == 0] = 0
    Image.fromarray(pixels).save(OUTPUT / filename, optimize=True)


